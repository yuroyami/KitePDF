package io.github.yuroyami.kitepdf.epub

/**
 * The normalization HarfBuzz applies to the characters of a run before GSUB (#316), with the
 * canonical decompositions and compositions of the Basic Multilingual Plane in Unicode 17:
 *
 * 1. A character decomposes when the font has no glyph for it. A character that marks follow
 *    decomposes as far as the font has glyphs for its parts.
 * 2. The marks go into canonical order, by [CombiningClass]. For Arabic and Syriac, the
 *    modifier marks of UTR #53, such as hamza above, then go first among the marks of their
 *    class (#318).
 * 3. A mark composes with the last character before it that has class 0, when no mark
 *    between them has the same or a higher class and the font has a glyph for the result.
 *
 * A shaper can change what decomposes and what composes, as the Indic shaper of HarfBuzz does.
 * Characters that move or join share the index of their first source, as HarfBuzz merges their
 * clusters.
 */
internal object Normalizer {

    /** Characters, each with the index in the word of the character it came from. */
    class Result(val codePoints: IntArray, val sources: IntArray)

    /**
     * Normalizes [codePoints], whose sources are [sources], for a font that has a glyph for a
     * character when [hasGlyph] says so. With [shortCircuit], as in HarfBuzz's default mode, a
     * character that no mark follows stays whole when the font has it. With [arabicMarks], the
     * modifier marks of UTR #53 go first among the marks of their class, as HarfBuzz's Arabic
     * shaper puts them. [decompose] gives the canonical decomposition of a character, one level
     * deep, and [compose] the character that two characters compose into.
     */
    fun normalize(
        codePoints: IntArray,
        sources: IntArray,
        hasGlyph: (Int) -> Boolean,
        shortCircuit: Boolean = true,
        arabicMarks: Boolean = false,
        decompose: (Int) -> IntArray? = ::decomposition,
        compose: (Int, Int) -> Int? = ::composition,
    ): Result {
        val n = codePoints.size
        val codes = ArrayList<Int>(n + 4)
        val srcs = ArrayList<Int>(n + 4)
        fun emit(cp: Int, source: Int) { codes += cp; srcs += source }
        fun decomposeCurrent(k: Int, shortest: Boolean) {
            val u = codePoints[k]
            if (shortest && hasGlyph(u)) return emit(u, sources[k])
            val parts = decomposeDeep(u, shortest, hasGlyph, decompose)
            if (parts != null) { for (part in parts) emit(part, sources[k]); return }
            if (!shortest && hasGlyph(u)) return emit(u, sources[k])
            // HarfBuzz draws a non-breaking hyphen with the glyph of the hyphen when it has to.
            if (u == 0x2011 && hasGlyph(0x2010)) return emit(0x2010, sources[k])
            emit(u, sources[k])
        }

        // 1. Decompose: the characters before a mark one by one, then each letter with its marks.
        var allSimple = true
        var idx = 0
        while (idx < n) {
            var end = idx + 1
            while (end < n && !isMark(codePoints[end])) end++
            if (end < n) end--
            while (idx < end) decomposeCurrent(idx++, shortCircuit)
            if (idx == n) break
            allSimple = false
            end = idx + 1
            while (end < n && isMark(codePoints[end])) end++
            // A cluster with a variation selector stays as it is.
            if ((idx until end).any { codePoints[it] in 0xFE00..0xFE0F }) {
                while (idx < end) { emit(codePoints[idx], sources[idx]); idx++ }
            } else {
                while (idx < end) decomposeCurrent(idx++, false)
            }
        }
        if (allSimple) return Result(codes.toIntArray(), srcs.toIntArray())

        // 2. Sort each run of marks by class, as HarfBuzz's insertion sort does.
        val classes = codes.map { CombiningClass.modified(it) }.toMutableList()
        var i = 0
        while (i < codes.size) {
            if (classes[i] == 0) { i++; continue }
            var end = i + 1
            while (end < codes.size && classes[end] != 0) end++
            if (end - i <= MAX_MARKS) {
                for (k in i + 1 until end) {
                    var j = k
                    while (j > i && classes[j - 1] > classes[k]) j--
                    if (j == k) continue
                    mergeSources(srcs, j, k + 1)
                    moveBefore(codes, srcs, classes, j, k, k + 1)
                }
                if (arabicMarks) moveModifierMarks(codes, srcs, classes, i, end)
            }
            i = end
        }

        // 3. Recompose each mark with the last starter, when nothing between them blocks it.
        val outCodes = ArrayList<Int>(codes.size)
        val outSrcs = ArrayList<Int>(codes.size)
        val outClasses = ArrayList<Int>(codes.size)
        var starter = 0
        for (k in codes.indices) {
            val cp = codes[k]
            if (k > 0 && isMark(cp)) {
                val last = outCodes.size - 1
                if (starter == last || outClasses[last] < classes[k]) {
                    val composed = compose(outCodes[starter], cp)
                    if (composed != null && hasGlyph(composed)) {
                        outCodes[starter] = composed
                        outClasses[starter] = CombiningClass.modified(composed)
                        // HarfBuzz's merge_out_clusters: the starter, what follows it, and what
                        // still comes with the source of the mark all take the first source.
                        var first = srcs[k]
                        for (j in starter..last) first = minOf(first, outSrcs[j])
                        var from = starter
                        while (from > 0 && outSrcs[from - 1] == outSrcs[from]) from--
                        for (j in from..last) outSrcs[j] = first
                        var next = k + 1
                        while (next < srcs.size && srcs[next] == srcs[k]) srcs[next++] = first
                        continue
                    }
                }
            }
            outCodes += cp
            outSrcs += srcs[k]
            outClasses += classes[k]
            if (classes[k] == 0) starter = outCodes.size - 1
        }
        return Result(outCodes.toIntArray(), outSrcs.toIntArray())
    }

    /** HarfBuzz sorts a run of marks only up to this length. */
    private const val MAX_MARKS = 32

    /**
     * HarfBuzz's merge_clusters: the characters from [start] to [end] take their first source,
     * and so do the neighbours that shared a source with the ends of the range.
     */
    private fun mergeSources(srcs: MutableList<Int>, start: Int, end: Int) {
        var from = start
        var to = end
        var first = srcs[from]
        for (i in from + 1 until to) first = minOf(first, srcs[i])
        if (first != srcs[to - 1]) while (to < srcs.size && srcs[to - 1] == srcs[to]) to++
        if (first != srcs[from]) while (from > 0 && srcs[from - 1] == srcs[from]) from--
        for (i in from until to) srcs[i] = first
    }

    /** Moves the characters from [i] to [j] before the one at [at], in all three lists. */
    private fun moveBefore(codes: MutableList<Int>, srcs: MutableList<Int>, classes: MutableList<Int>, at: Int, i: Int, j: Int) {
        for (list in listOf(codes, srcs, classes)) {
            val moved = list.subList(i, j).toList()
            list.subList(i, j).clear()
            list.addAll(at, moved)
        }
    }

    /**
     * Moves the modifier marks of UTR #53 at the start of the class 220 marks, and then those at
     * the start of the class 230 marks, before the other marks of the sorted run from [runStart]
     * to [end], as HarfBuzz's reorder_marks_arabic does. The marks it moves take the classes 25
     * and 26, below every other Arabic mark, so that no later mark composes past them.
     */
    private fun moveModifierMarks(codes: MutableList<Int>, srcs: MutableList<Int>, classes: MutableList<Int>, runStart: Int, end: Int) {
        var start = runStart
        var i = runStart
        for (cc in intArrayOf(220, 230)) {
            while (i < end && classes[i] < cc) i++
            if (i == end) break
            if (classes[i] > cc) continue
            var j = i
            while (j < end && classes[j] == cc && codes[j] in MODIFIER_MARKS) j++
            if (i == j) continue
            mergeSources(srcs, start, j)
            moveBefore(codes, srcs, classes, start, i, j)
            val newStart = start + j - i
            while (start < newStart) classes[start++] = if (cc == 220) 25 else 26
            i = j
        }
    }

    /** The modifier combining marks of UTR #53. */
    private val MODIFIER_MARKS = setOf(
        0x0654, 0x0655, 0x0658, 0x06DC, 0x06E3, 0x06E7, 0x06E8, 0x08CA, 0x08CB, 0x08CD, 0x08CE, 0x08CF, 0x08D3, 0x08F3,
    )

    /** The parts of [ab] as HarfBuzz's decompose finds them for the font, or null to keep it whole. */
    private fun decomposeDeep(ab: Int, shortest: Boolean, hasGlyph: (Int) -> Boolean, decompose: (Int) -> IntArray?): IntArray? {
        val parts = decompose(ab) ?: return null
        val a = parts[0]
        val b = if (parts.size > 1) parts[1] else 0
        if (b != 0 && !hasGlyph(b)) return null
        val hasA = hasGlyph(a)
        if (shortest && hasA) return parts
        decomposeDeep(a, shortest, hasGlyph, decompose)?.let { return if (b != 0) it + b else it }
        return if (hasA) parts else null
    }

    /** True for a character of general category Mn, Mc or Me, or one with a combining class. */
    fun isMark(cp: Int): Boolean = when (cp.toChar().category) {
        CharCategory.NON_SPACING_MARK, CharCategory.COMBINING_SPACING_MARK, CharCategory.ENCLOSING_MARK -> true
        else -> CombiningClass.canonical(cp) != 0
    }

    /** The canonical decomposition of [cp], one level deep, or null for a character that has none. */
    fun decomposition(cp: Int): IntArray? = decompositions[cp]

    /** The primary composite of [a] and [b], or null when they do not compose. */
    fun composition(a: Int, b: Int): Int? = compositions[(a shl 16) or b]

    private val decompositions: Map<Int, IntArray> by lazy {
        val out = HashMap<Int, IntArray>(DECOMPOSITIONS.length / 13 * 2)
        for (r in 0 until DECOMPOSITIONS.length / 13) {
            val cp = hex(r * 13)
            val b = hex(r * 13 + 8)
            out[cp] = if (b == 0) intArrayOf(hex(r * 13 + 4)) else intArrayOf(hex(r * 13 + 4), b)
        }
        out
    }

    private val compositions: Map<Int, Int> by lazy {
        val out = HashMap<Int, Int>(DECOMPOSITIONS.length / 13 * 2)
        for (r in 0 until DECOMPOSITIONS.length / 13) {
            if (DECOMPOSITIONS[r * 13 + 12] == 'c') out[(hex(r * 13 + 4) shl 16) or hex(r * 13 + 8)] = hex(r * 13)
        }
        out
    }

