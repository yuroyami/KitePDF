#!/usr/bin/env python3
"""Write kitepdf-core's DiacriticFolding.kt from the Unicode Character Database.

  python3 tools/text/generate_diacritic_folding.py UnicodeData.txt

Each BMP character whose full canonical decomposition is one base character that is no mark,
followed by nothing but non-spacing marks (general category Mn), maps to that base. A search
that ignores diacritics folds the text through it and drops the marks, as pdf.js does.
"""
import sys
from pathlib import Path

OUT = Path(__file__).resolve().parents[2] / "kitepdf-core/src/io/github/yuroyami/kitepdf/core/DiacriticFolding.kt"


def main(path):
    category = {}
    decomposition = {}
    for line in open(path, encoding="utf-8"):
        f = line.split(";")
        cp = int(f[0], 16)
        category[cp] = f[2]
        d = f[5].strip()
        if d and not d.startswith("<"):
            decomposition[cp] = [int(x, 16) for x in d.split()]

    def full(cp):
        if cp not in decomposition:
            return [cp]
        out = []
        for part in decomposition[cp]:
            out += full(part)
        return out

    pairs = []
    for cp in sorted(decomposition):
        if cp > 0xFFFF:
            continue
        parts = full(cp)
        base, marks = parts[0], parts[1:]
        if not marks or base > 0xFFFF or category.get(base, "").startswith("M"):
            continue
        if all(category.get(m) == "Mn" for m in marks):
            pairs.append((cp, base))
    data = "".join("%04X%04X" % p for p in pairs)
    chunks = [data[i:i + 96] for i in range(0, len(data), 96)]
    body = "\n".join('        "%s" +' % c for c in chunks)[:-2]
    OUT.write_text(
        "package io.github.yuroyami.kitepdf.core\n\n"
        "// Generated by tools/text/generate_diacritic_folding.py from the Unicode 16.0.0 UnicodeData.txt.\n"
        "// Do not edit by hand.\n\n"
        "/**\n"
        " * The base letter of each precomposed BMP character whose canonical decomposition is a base\n"
        " * followed by non-spacing marks alone, so `é` folds to `e` and `ǖ` to `u` (#943).\n"
        " */\n"
        "internal object DiacriticFolding {\n\n"
        "    private val bases: Map<Char, Char> by lazy {\n"
        "        val out = HashMap<Char, Char>(DATA.length / 8 * 2)\n"
        "        for (i in 0 until DATA.length / 8) {\n"
        "            out[DATA.substring(i * 8, i * 8 + 4).toInt(16).toChar()] = DATA.substring(i * 8 + 4, i * 8 + 8).toInt(16).toChar()\n"
        "        }\n"
        "        out\n"
        "    }\n\n"
        "    /** The base letter of [c], or [c] itself. */\n"
        "    fun base(c: Char): Char = bases[c] ?: c\n\n"
        "    /** Whether [c] is a non-spacing mark, which a fold drops. */\n"
        "    fun isMark(c: Char): Boolean = c.category == CharCategory.NON_SPACING_MARK\n\n"
        "    private const val DATA: String =\n%s\n}\n" % body
    )
    print("wrote", OUT, len(pairs), "pairs")


if __name__ == "__main__":
    main(sys.argv[1])
