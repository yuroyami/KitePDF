#!/usr/bin/env python3
"""Write kitepdf-core's SingleByteEncodings.kt from the WHATWG Encoding Standard's data.

  curl -O https://encoding.spec.whatwg.org/indexes.json
  curl -O https://encoding.spec.whatwg.org/encodings.json
  python3 tools/text/generate_single_byte_encodings.py indexes.json encodings.json

Each single-byte encoding keeps its 128 code points from 0x80, U+FFFD where the index has none,
and the labels that name it (WHATWG Encoding, 4.2 and 9).
"""
import json
import sys
from pathlib import Path

OUT = Path(__file__).resolve().parents[2] / "kitepdf-core/src/io/github/yuroyami/kitepdf/core/text/SingleByteEncodings.kt"


def main(indexes_path, encodings_path):
    indexes = json.load(open(indexes_path))
    groups = json.load(open(encodings_path))
    single = next(g for g in groups if g["heading"] == "Legacy single-byte encodings")["encodings"]
    labels = []
    tables = []
    for enc in single:
        name = enc["name"]
        # ISO-8859-8-I differs from ISO-8859-8 in its direction only, and shares its index.
        index = indexes["iso-8859-8" if name == "ISO-8859-8-I" else name.lower()]
        assert len(index) == 128, name
        labels.append(name + " " + " ".join(enc["labels"]))
        chars = "".join("\\u%04X" % (cp if cp is not None else 0xFFFD) for cp in index)
        tables.append('        "%s" to "%s",' % (name, chars))
    text = (
        "package io.github.yuroyami.kitepdf.core.text\n\n"
        "// Generated by tools/text/generate_single_byte_encodings.py from the WHATWG Encoding Standard's\n"
        "// indexes.json and encodings.json. Do not edit by hand.\n\n"
        "/**\n"
        " * The legacy single-byte encodings of the WHATWG Encoding Standard: each one's labels, and the\n"
        " * character of each byte from 0x80 (U+FFFD for a byte the index leaves out), so a declared\n"
        " * windows-1251 or KOI8-R document decodes as a browser decodes it (#878).\n"
        " */\n"
        "internal object SingleByteEncodings {\n\n"
        "    /** Each label, trimmed and in lower case, to the name of its encoding. */\n"
        "    private val names: Map<String, String> by lazy {\n"
        "        val out = HashMap<String, String>()\n"
        "        for (line in LABELS.split('\\n')) {\n"
        "            val words = line.split(' ')\n"
        "            for (label in words.subList(1, words.size)) out[label] = words[0]\n"
        "        }\n"
        "        out\n"
        "    }\n\n"
        "    /** The encoding [label] names, or null when it names no single-byte encoding. */\n"
        "    fun forLabel(label: String): String? = names[label]\n\n"
        "    /** The 128 characters of [name]'s bytes 0x80 to 0xFF. */\n"
        "    fun high(name: String): String? = TABLES[name]\n\n"
        "    private const val LABELS: String = \"%s\"\n\n"
        "    private val TABLES: Map<String, String> = mapOf(\n%s\n    )\n"
        "}\n"
    ) % ("\\n".join(labels), "\n".join(tables))
    OUT.write_text(text)
    print("wrote", OUT, len(single), "encodings")


if __name__ == "__main__":
    main(sys.argv[1], sys.argv[2])
